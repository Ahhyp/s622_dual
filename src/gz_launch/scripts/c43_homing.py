"""C4.3 S4 startup homing: dual_home -> q_grasp12, then hand over to the QP.

The robot is spawned at dual_home so the gripper does not start wrapped around
the sample.  The QP transport still requires q_grasp12 (home_q and the frozen
relative target), so two arm JTCs move there first; only then is the QP
activated.  The JTCs are inactive afterwards; the QP owns the arm joints.
"""

