MOVE_S = 8.0


class Homing(Node):
    def __init__(self):
        super().__init__("c43_s4_homing")
        self.left = ActionClient(self, FollowJointTrajectory,
                                 "/left_arm_controller/follow_joint_trajectory")
        self.right = ActionClient(self, FollowJointTrajectory,
                                  "/right_arm_controller/follow_joint_trajectory")
        self.left_hand = ActionClient(
            self, FollowJointTrajectory,
            "/left_hand_controller/follow_joint_trajectory")
        self.right_hand = ActionClient(
            self, FollowJointTrajectory,
            "/right_hand_controller/follow_joint_trajectory")
        self.switch = self.create_client(
            SwitchController, "/controller_manager/switch_controller")
        self.q = {}
        self.create_subscription(JointState, "/joint_states", self._on_joints, 20)

    def _on_joints(self, msg):
        for name, pos in zip(msg.name, msg.position):
            self.q[name] = pos

    def current(self, names):
        for _ in range(200):
            if all(n in self.q for n in names):
                return [self.q[n] for n in names]
            rclpy.spin_once(self, timeout_sec=0.05)
        raise RuntimeError("no /joint_states sample for the arm joints")

    def wait(self, client, what):
        # ActionClient has wait_for_server(); service Client has wait_for_service().
        if isinstance(client, ActionClient):
            ready = client.wait_for_server(timeout_sec=120.0)
        else:
            ready = client.wait_for_service(timeout_sec=120.0)
        if not ready:
            raise RuntimeError(f"{what} did not become ready")
        self.get_logger().info(f"{what} ready")

    def send_goal(self, client, joints, q, label, duration_s=MOVE_S):
        goal = FollowJointTrajectory.Goal()
        traj = JointTrajectory()
        traj.joint_names = joints
        pt = JointTrajectoryPoint()
        pt.positions = q
        pt.time_from_start.sec = int(duration_s)
        pt.time_from_start.nanosec = 0
        traj.points.append(pt)
        goal.trajectory = traj
        self.get_logger().info(f"moving {label} to q_grasp12 over {duration_s:.1f} s")
        fut = client.send_goal_async(goal)
        rclpy.spin_until_future_complete(self, fut, timeout_sec=30.0)
        handle = fut.result()
        if handle is None or not handle.accepted:
            raise RuntimeError(f"{label} goal was not accepted")
        return handle

    def send_traj(self, client, joints, points, duration_s, label):
        goal = FollowJointTrajectory.Goal()
        traj = JointTrajectory()
        traj.joint_names = joints
        n = len(points)
        for i, q in enumerate(points):
            pt = JointTrajectoryPoint()
            pt.positions = q
            t = duration_s * (i + 1) / n
            pt.time_from_start.sec = int(t)
            pt.time_from_start.nanosec = int((t - int(t)) * 1e9)
            traj.points.append(pt)
        goal.trajectory = traj
        self.get_logger().info(
            f"moving {label}: {n} IK points over {duration_s:.1f} s")
        fut = client.send_goal_async(goal)
        rclpy.spin_until_future_complete(self, fut, timeout_sec=30.0)
        handle = fut.result()
        if handle is None or not handle.accepted:
            raise RuntimeError(f"{label} goal was not accepted")
        self.wait_result(handle, label)

    def wait_result(self, handle, label):
        rf = handle.get_result_async()
        rclpy.spin_until_future_complete(self, rf, timeout_sec=90.0)
        result = rf.result()
        if result is None or result.result.error_code != 0:
            code = None if result is None else result.result.error_code
            raise RuntimeError(f"{label} trajectory failed: error_code={code}")
        self.get_logger().info(f"{label} reached q_grasp12")

    def pre_grasp_mode(self):
        import json
        target_file = os.path.join(
            "/workspace", "docs", "双臂协同", "双臂协同运动控制与优化",
            "T1_QP满速定位_20261029", "pre_grasp_targets.json")
        with open(target_file, "w") as f:
            json.dump({
                "h_m": 0.05,
                "pre_left": PRE_LEFT, "pre_right": PRE_RIGHT,
                "descent_left": DESCENT_LEFT, "descent_right": DESCENT_RIGHT,
                "stage1_order": "right_first", "stage1_s_per_arm": 8.0, "stage2_s": 6.0,
            }, f, indent=2)
        self.get_logger().info(f"pre-grasp targets written to {target_file}")
        # Experiment 2.4-C: right first, then left.  Offline FCL showed this
        # removes the simultaneous left_finger1/right_finger2 collision.
        hR = self.send_goal(self.right, RIGHT_JOINTS, PRE_RIGHT,
                            "right pre_grasp first (TCP +0.05 m)", 8.0)
        self.wait_result(hR, "right pre_grasp first")
        hL = self.send_goal(self.left, LEFT_JOINTS, PRE_LEFT,
                            "left pre_grasp second (TCP +0.05 m)", 8.0)
        self.wait_result(hL, "left pre_grasp second")
        self.send_traj(self.left, LEFT_JOINTS, DESCENT_LEFT, 6.0,
                       "left Cartesian descent to q_grasp12")
        self.send_traj(self.right, RIGHT_JOINTS, DESCENT_RIGHT, 6.0,
                       "right Cartesian descent to q_grasp12")
        self.get_logger().info("PRE_GRASP_HOMING COMPLETE: q_pre -> q_grasp12")

    def run(self):
        self.wait(self.switch, "controller_manager switch_controller")
        self.wait(self.left, "left_arm_controller")
        self.wait(self.right, "right_arm_controller")
        self.wait(self.left_hand, "left_hand_controller")
        self.wait(self.right_hand, "right_hand_controller")
        # Both grippers must be visibly open at the end of homing.  The left one
        # was opened by its initial value; the right one used to stay at 0.0,
        # which is CLOSED for these prismatic finger joints.  Command both
        # explicitly so a controller startup ordering cannot leave one shut.
        hand_open = ["left_finger1_joint", "left_finger2_joint"]
        h = self.send_goal(self.left_hand, hand_open, [0.0305, -0.0305],
                           "left hand open", 1.5)
        self.wait_result(h, "left hand open")
        hand_open = ["right_finger1_joint", "right_finger2_joint"]
        h = self.send_goal(self.right_hand, hand_open, [0.0305, -0.0305],
                           "right hand open", 1.5)
        self.wait_result(h, "right hand open")

        if os.environ.get("C43_PRE_GRASP_HOMING", "0") == "1":
            self.pre_grasp_mode()
        else:
            left_handle = self.send_goal(self.left, LEFT_JOINTS, LEFT_Q, "left arm")
            right_handle = self.send_goal(self.right, RIGHT_JOINTS, RIGHT_Q, "right arm")
            self.wait_result(left_handle, "left arm")
            self.wait_result(right_handle, "right arm")
            for it in range(8):
                qL = self.current(LEFT_JOINTS)
                qR = self.current(RIGHT_JOINTS)
                eL = [LEFT_Q[i] - qL[i] for i in range(6)]
                eR = [RIGHT_Q[i] - qR[i] for i in range(6)]
                worst = max(max(abs(x) for x in eL), max(abs(x) for x in eR))
                self.get_logger().info(
                    f"homing residual {it}: max|q-q_grasp12|={worst:.4f} rad")
                if worst < 0.003:
                    break
                tgtL = [LEFT_Q[i] + 0.4 * eL[i] for i in range(6)]
                tgtR = [RIGHT_Q[i] + 0.4 * eR[i] for i in range(6)]
                hL = self.send_goal(self.left, LEFT_JOINTS, tgtL,
                                    f"left correction {it}", 3.0)
                hR = self.send_goal(self.right, RIGHT_JOINTS, tgtR,
                                    f"right correction {it}", 3.0)
                self.wait_result(hL, f"left correction {it}")
                self.wait_result(hR, f"right correction {it}")
                for _ in range(20):
                    rclpy.spin_once(self, timeout_sec=0.05)

        if os.environ.get("C43_HOMING_NO_QP", "0") == "1":
            # Diagnostic 2.2: leave the arm JTCs holding q_grasp12.  The QP stays
            # inactive, and no transport/attach is started.
            self.get_logger().info(
                "HOMING COMPLETE (QP disabled for diagnostic; arm JTCs hold)")
            return

        req = SwitchController.Request()
        req.deactivate_controllers = ["left_arm_controller", "right_arm_controller"]
        req.activate_controllers = ["dual_arm_qp_controller"]
        req.strictness = SwitchController.Request.STRICT
        fut = self.switch.call_async(req)
        rclpy.spin_until_future_complete(self, fut, timeout_sec=60.0)
        resp = fut.result()
        if resp is None or not resp.ok:
            raise RuntimeError("controller switch to QP failed")
        self.get_logger().info("HOMING COMPLETE: arms at q_grasp12, QP active")


def main():
    rclpy.init()
    node = Homing()
    try:
        node.run()
    except Exception as exc:  # noqa: BLE001 - a startup failure must be visible
        node.get_logger().error(f"HOMING FAILED: {exc}")
        node.destroy_node()
        rclpy.shutdown()
        return 1
    node.destroy_node()
    rclpy.shutdown()
    return 0


if __name__ == "__main__":
    sys.exit(main())
