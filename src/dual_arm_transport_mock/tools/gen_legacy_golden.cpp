// C4.3 S3 -- golden generator for the LEGACY-equivalence test (S3-T5c).
//
// This program is deliberately NOT part of the colcon build: it must be compiled
// against the HEAD (pre-S3) headers and linked against the HEAD library, i.e.
//
//   git show HEAD:src/dual_arm_qp_core/include/dual_arm_qp_core/dual_arm_qp.hpp \
//     > /tmp/s3_w0/old_include/dual_arm_qp_core/dual_arm_qp.hpp
//   git show HEAD:src/dual_arm_qp_core/include/dual_arm_qp_core/qp_types.hpp \
//     > /tmp/s3_w0/old_include/dual_arm_qp_core/qp_types.hpp
//   g++ -std=c++17 -O2 -I/tmp/s3_w0/old_include -Isrc/dual_arm_kinematics/include \
//       -Isrc/dual_arm_transport_mock/tools \
//       -I/usr/include/eigen3 $(pkg-config --cflags-only-I ...) \
//       tools/gen_legacy_golden.cpp /tmp/s3_w0/libdual_arm_qp_core.HEAD.so \
//       -ldual_arm_kinematics -o /tmp/s3_w0/gen_golden
//   /tmp/s3_w0/gen_golden > src/dual_arm_transport_mock/test/golden_legacy_dq.hpp
//
// Rationale: DualArmQpResult gained members in C4.3 S3, so a test binary built
// against the NEW header cannot link the OLD library (layout mismatch).  We
// capture the old outputs once, here, with the old header.
#include <cstdio>

#include "dual_arm_qp_core/dual_arm_qp.hpp"
#include "legacy_cases.hpp"

namespace {

using legacy_golden::CaseSpec;
using legacy_golden::Kind;
using legacy_golden::kCases;

dual_arm_qp::DualArmQpParams makeParams(const CaseSpec& c) {
    dual_arm_qp::DualArmQpParams p;
    dual_arm_qp::defaultS622Limits(&p.q_min, &p.q_max, &p.v_max);
    p.w_obj = c.w_obj;
    // A physically sane object-axis penalty for the w_obj == 1 cases (the
    // historical default 1e-6 would make the object task toothless, but for a
    // bit-identity test any value works as long as it is fixed).
    p.w_slack_obj = (c.w_obj > 0.0) ? 1e3 : 1e-6;
    return p;
}

}  // namespace

int main() {
    const dual_arm::DualArmKinematics kin;
    const dual_arm::Q12 q = legacy_golden::graspQ();

    std::printf("// GENERATED by tools/gen_legacy_golden.cpp -- DO NOT EDIT.\n");
    std::printf("// Captured from libdual_arm_qp_core at git HEAD 6e5cb26 (pre-C4.3-S3).\n");
    std::printf("// Values are exact hex float literals (%%a) so comparison is bitwise.\n");
    std::printf("#ifndef DUAL_ARM_TRANSPORT_MOCK__TEST__GOLDEN_LEGACY_DQ_HPP_\n");
    std::printf("#define DUAL_ARM_TRANSPORT_MOCK__TEST__GOLDEN_LEGACY_DQ_HPP_\n\n");
    std::printf("namespace legacy_golden {\n\n");
    std::printf("struct GoldenDq {\n  const char* name;\n  bool converged;\n");
    std::printf("  double dq[12];\n};\n\n");
    std::printf("inline constexpr GoldenDq kGolden[] = {\n");

    for (const CaseSpec& c : kCases) {
        dual_arm_qp::DualArmQpParams p = makeParams(c);
        dual_arm_qp::DualArmQp qp(kin, p);
        qp.setWarmStart(c.warm_start);

        // Both targets are *perturbed* away from the current state so the QP has
        // a non-trivial problem to solve.
        const dual_arm::Iso3 ltr_target =
            kin.leftTright(q) * legacy_golden::expTwist(c.relative_offset);
        const dual_arm::Iso3 obj_target =
            kin.worldTobject(q) * legacy_golden::expTwist(c.object_offset);
        dual_arm::Vec6 ff;
        ff << c.ff[0], c.ff[1], c.ff[2], c.ff[3], c.ff[4], c.ff[5];

        dual_arm_qp::DualArmQpResult r;
        switch (c.kind) {
            case Kind::kRelativeOnly:
                r = qp.solve(q, ltr_target);
                break;
            case Kind::kRelativeAndObject:
                r = qp.solve(q, ltr_target, obj_target);
                break;
            case Kind::kWithFeedforward:
                r = qp.solve(q, ltr_target, obj_target, ff);
                break;
        }

        std::printf("    {\"%s\", %s, {", c.name, r.converged ? "true" : "false");
        for (int i = 0; i < 12; ++i) {
            std::printf("%s%a", (i == 0) ? "" : ", ", r.dq[i]);
        }
        std::printf("}},\n");
    }

    std::printf("};\n\n}  // namespace legacy_golden\n\n");
    std::printf("#endif  // DUAL_ARM_TRANSPORT_MOCK__TEST__GOLDEN_LEGACY_DQ_HPP_\n");
    return 0;
}
